-- Idempotent orders: tables and functions for placing an order that survives a lost response and a
-- double tap. Every write goes through a plpgsql function, one transaction each, called only by the
-- server (the service_role on Supabase). The functions answer with jsonb: an `outcome` and, where it
-- applies, the order as stored. A shape error raises SQLSTATE 22023 before anything is written.
--
-- Rerunnable: tables use `if not exists`, functions `create or replace`.

-- ─── Tables ──────────────────────────────────────────────────────────────────────────────────────

create table if not exists products (
  id          bigint generated always as identity primary key,
  name        text    not null check (char_length(name) between 1 and 200),
  price_cents integer not null check (price_cents >= 0),
  active      boolean not null default true
);

-- Units on hand. The check is the last line of defense: confirm_order refuses an order it cannot
-- cover before it writes, and a write that would go below zero fails here anyway.
create table if not exists stock (
  product_id bigint  primary key references products (id) on delete cascade,
  on_hand    integer not null check (on_hand >= 0)
);

create table if not exists orders (
  id              bigint generated always as identity primary key,
  -- The key of one user action, generated by the browser. One order per key, enforced here: the
  -- lookup in place_order is the fast path, this constraint is what holds under a race.
  idempotency_key text not null check (idempotency_key ~ '^[A-Za-z0-9_-]{16,64}$'),
  customer_id     text not null check (char_length(customer_id) between 1 and 64),
  -- product x quantity of the request that placed the order. A resend is compared with this, not
  -- with the current lines, so an edit made in between does not turn a resend into a conflict.
  fingerprint     text not null,
  status          text not null default 'pending' check (status in ('pending', 'confirmed')),
  version         integer not null default 1 check (version >= 1),
  total_cents     bigint not null check (total_cents >= 0),
  created_at      timestamptz not null default now(),
  confirmed_at    timestamptz,
  -- The key of the confirm that claimed the order: a resend of that confirm is told it went in.
  confirm_key     text check (confirm_key ~ '^[A-Za-z0-9_-]{16,64}$'),
  constraint orders_idempotency_key_unique unique (idempotency_key),
  constraint orders_confirmed_complete check (
    (status = 'confirmed') = (confirm_key is not null and confirmed_at is not null)
  )
);

create table if not exists order_lines (
  order_id         bigint  not null references orders (id) on delete cascade,
  product_id       bigint  not null references products (id),
  quantity         integer not null check (quantity between 1 and 9999),
  unit_price_cents integer not null check (unit_price_cents >= 0),
  primary key (order_id, product_id)
);

-- ─── Helpers ─────────────────────────────────────────────────────────────────────────────────────

-- Validates a line list and raises 22023 on any problem. 1 to 200 lines, each an object with an
-- integer product_id and an integer quantity from 1 to 9999, no product twice. Nothing is coerced:
-- a quantity of "2" or 2.5 is an error, not a 2.
create or replace function validate_lines(p_lines jsonb)
returns void
language plpgsql
immutable
set search_path = public
as $$
begin
  if jsonb_typeof(p_lines) is distinct from 'array' or jsonb_array_length(p_lines) not between 1 and 200 then
    raise exception 'lines must be an array of 1 to 200 items' using errcode = '22023';
  end if;
  -- coalesce: a missing key is NULL, and a NULL in this OR would let the line through.
  if exists (
    select 1 from jsonb_array_elements(p_lines) as l
    where jsonb_typeof(l) <> 'object'
       or coalesce(jsonb_typeof(l->'product_id'), '') <> 'number'
       or coalesce(l->>'product_id', '') !~ '^[1-9][0-9]{0,15}$'
       or coalesce(jsonb_typeof(l->'quantity'), '') <> 'number'
       or coalesce(l->>'quantity', '') !~ '^[1-9][0-9]{0,3}$'
  ) then
    raise exception 'every line needs an integer product_id and a quantity from 1 to 9999' using errcode = '22023';
  end if;
  if (select count(distinct (l->>'product_id')::bigint) from jsonb_array_elements(p_lines) as l)
     <> jsonb_array_length(p_lines) then
    raise exception 'a product appears twice' using errcode = '22023';
  end if;
end $$;

-- product x quantity, ordered by product id: "3x2,10x1". `fingerprint` in src/lines.ts computes the
-- same string, and test/lines.test.ts checks the two agree. Call it on validated lines only.
create or replace function order_fingerprint(p_lines jsonb)
returns text
language sql
immutable
set search_path = public
as $$
  select string_agg((l->>'product_id')::bigint::text || 'x' || (l->>'quantity')::int::text, ','
                    order by (l->>'product_id')::bigint)
    from jsonb_array_elements(p_lines) as l
$$;

-- The order as the functions return it, with its lines in product order.
create or replace function order_view(p_order_id bigint)
returns jsonb
language sql
stable
set search_path = public
as $$
  select jsonb_build_object(
           'id', o.id, 'idempotency_key', o.idempotency_key, 'customer_id', o.customer_id,
           'fingerprint', o.fingerprint, 'status', o.status, 'version', o.version,
           'total_cents', o.total_cents, 'created_at', o.created_at,
           'confirmed_at', o.confirmed_at, 'confirm_key', o.confirm_key,
           'lines', coalesce((
             select jsonb_agg(jsonb_build_object('product_id', l.product_id, 'quantity', l.quantity,
                                                 'unit_price_cents', l.unit_price_cents)
                              order by l.product_id)
               from order_lines as l where l.order_id = o.id), '[]'::jsonb))
    from orders as o where o.id = p_order_id
$$;

-- The resend window: an order placed this long ago or less can be answered as a resend of the
-- request that placed it. A resend after a lost response comes within minutes; an old key with the
-- same cart is more likely a new order, and answering it with the old order would swallow that order.
-- place_order and find_order both use it, so the client never applies a window of its own.
create or replace function in_resend_window(p_created_at timestamptz)
returns boolean
language sql
stable
set search_path = public
as $$
  select p_created_at >= now() - interval '60 minutes'
$$;

-- What a request with a key that is already stored gets back, in this order of checks:
--   key_taken      the key belongs to another customer; that order is not shown.
--   key_expired    why 'age': the order is outside the resend window. why 'not_pending': it is
--                  inside the window but no longer pending, so it cannot be answered as a fresh
--                  resend. The client may report the second as its own order only when an earlier
--                  attempt of the same call was lost (src/client.ts).
--   key_reused     same customer, recent, but other products or quantities: what changed was NOT
--                  saved, and the caller must not say "sent".
--   already_placed the same request again. Nothing is written.
create or replace function resend_outcome(p_order orders, p_customer text, p_fingerprint text)
returns jsonb
language plpgsql
stable
set search_path = public
as $$
begin
  if p_order.customer_id <> p_customer then
    return jsonb_build_object('outcome', 'key_taken');
  end if;
  if not in_resend_window(p_order.created_at) then
    return jsonb_build_object('outcome', 'key_expired', 'why', 'age', 'order', order_view(p_order.id));
  end if;
  if p_order.status <> 'pending' then
    return jsonb_build_object('outcome', 'key_expired', 'why', 'not_pending', 'order', order_view(p_order.id));
  end if;
  if p_order.fingerprint <> p_fingerprint then
    return jsonb_build_object('outcome', 'key_reused', 'order', order_view(p_order.id));
  end if;
  return jsonb_build_object('outcome', 'already_placed', 'order', order_view(p_order.id));
end $$;

create or replace function validate_key(p_key text)
returns void
language plpgsql
immutable
set search_path = public
as $$
begin
  if p_key is null or p_key !~ '^[A-Za-z0-9_-]{16,64}$' then
    raise exception 'invalid key' using errcode = '22023';
  end if;
end $$;

-- ─── place_order ─────────────────────────────────────────────────────────────────────────────────

-- Places one order for one user action, identified by p_key. Prices come from products, never from
-- the request. Outcomes: placed | already_placed | key_reused | key_expired | key_taken |
-- unavailable (with product_ids; nothing written). The key is looked up before the products are
-- read, so a resend of an order that went in is never told "product not available".
create or replace function place_order(p_key text, p_customer text, p_lines jsonb)
returns jsonb
language plpgsql
volatile
security invoker
set search_path = public
set lock_timeout = '5s'
as $$
declare
  v_fp         text;
  v_existing   orders;
  v_ids        bigint[];
  v_missing    jsonb;
  v_total      bigint;
  v_id         bigint;
  v_constraint text;
begin
  perform validate_key(p_key);
  if p_customer is null or char_length(p_customer) not between 1 and 64 then
    raise exception 'invalid customer' using errcode = '22023';
  end if;
  perform validate_lines(p_lines);
  v_fp := order_fingerprint(p_lines);

  select * into v_existing from orders where idempotency_key = p_key;
  if found then
    return resend_outcome(v_existing, p_customer, v_fp);
  end if;

  select array_agg((l->>'product_id')::bigint order by (l->>'product_id')::bigint) into v_ids
    from jsonb_array_elements(p_lines) as l;
  -- Share locks in id order: a price or an `active` flag cannot change under this transaction, and
  -- two transactions that lock overlapping sets always take them in the same order.
  perform 1 from products where id = any (v_ids) order by id for share;
  select coalesce(jsonb_agg(want.id order by want.id), '[]'::jsonb) into v_missing
    from unnest(v_ids) as want (id)
    left join products as p on p.id = want.id and p.active
   where p.id is null;
  if jsonb_array_length(v_missing) > 0 then
    return jsonb_build_object('outcome', 'unavailable', 'product_ids', v_missing);
  end if;
  select sum(p.price_cents::bigint * (l->>'quantity')::int) into v_total
    from jsonb_array_elements(p_lines) as l
    join products as p on p.id = (l->>'product_id')::bigint;

  begin
    insert into orders (idempotency_key, customer_id, fingerprint, total_cents)
    values (p_key, p_customer, v_fp, v_total)
    returning id into v_id;
  exception when unique_violation then
    -- Two requests with the same key at once: this one waited for the other, which committed the
    -- order after this one's lookup. Answer with that order. A violation of any other constraint is
    -- not a resend and goes on as an error: "already placed" without an order would be a lie.
    get stacked diagnostics v_constraint = constraint_name;
    if v_constraint is distinct from 'orders_idempotency_key_unique' then
      raise;
    end if;
    select * into v_existing from orders where idempotency_key = p_key;
    if not found then
      raise;
    end if;
    return resend_outcome(v_existing, p_customer, v_fp);
  end;

  -- If a line fails, the exception undoes the insert above too: no order is left without lines.
  insert into order_lines (order_id, product_id, quantity, unit_price_cents)
  select v_id, p.id, (l->>'quantity')::int, p.price_cents
    from jsonb_array_elements(p_lines) as l
    join products as p on p.id = (l->>'product_id')::bigint;

  return jsonb_build_object('outcome', 'placed', 'order', order_view(v_id));
end $$;

-- The re-read of the retry protocol: did the order for this key go in? found (with
-- within_window, the same rule place_order applies) | not_found | key_taken. Read only, so the
-- client can ask it when place_order keeps failing.
create or replace function find_order(p_key text, p_customer text)
returns jsonb
language plpgsql
stable
security invoker
set search_path = public
as $$
declare
  v_order orders;
begin
  perform validate_key(p_key);
  select * into v_order from orders where idempotency_key = p_key;
  if not found then
    return jsonb_build_object('outcome', 'not_found');
  end if;
  if v_order.customer_id <> p_customer then
    return jsonb_build_object('outcome', 'key_taken');
  end if;
  return jsonb_build_object('outcome', 'found', 'within_window', in_resend_window(v_order.created_at),
                            'order', order_view(v_order.id));
end $$;

-- ─── edit_order ──────────────────────────────────────────────────────────────────────────────────

-- Replaces the lines of a pending order, if the caller saw the current version. Outcomes: edited |
-- not_found | not_pending | version_conflict (with current_version) | unavailable. The row lock
-- makes a confirm that arrives meanwhile wait, and then see the new version.
create or replace function edit_order(p_order_id bigint, p_expected_version integer, p_lines jsonb)
returns jsonb
language plpgsql
volatile
security invoker
set search_path = public
set lock_timeout = '5s'
as $$
declare
  v_order   orders;
  v_ids     bigint[];
  v_missing jsonb;
  v_total   bigint;
begin
  if p_order_id is null or p_expected_version is null then
    raise exception 'missing order id or version' using errcode = '22023';
  end if;
  perform validate_lines(p_lines);

  select * into v_order from orders where id = p_order_id for update;
  if not found then
    return jsonb_build_object('outcome', 'not_found');
  end if;
  if v_order.status <> 'pending' then
    return jsonb_build_object('outcome', 'not_pending', 'status', v_order.status);
  end if;
  if v_order.version <> p_expected_version then
    return jsonb_build_object('outcome', 'version_conflict', 'current_version', v_order.version);
  end if;

  select array_agg((l->>'product_id')::bigint order by (l->>'product_id')::bigint) into v_ids
    from jsonb_array_elements(p_lines) as l;
  perform 1 from products where id = any (v_ids) order by id for share;
  select coalesce(jsonb_agg(want.id order by want.id), '[]'::jsonb) into v_missing
    from unnest(v_ids) as want (id)
    left join products as p on p.id = want.id and p.active
   where p.id is null;
  if jsonb_array_length(v_missing) > 0 then
    return jsonb_build_object('outcome', 'unavailable', 'product_ids', v_missing);
  end if;

  delete from order_lines where order_id = p_order_id;
  insert into order_lines (order_id, product_id, quantity, unit_price_cents)
  select p_order_id, p.id, (l->>'quantity')::int, p.price_cents
    from jsonb_array_elements(p_lines) as l
    join products as p on p.id = (l->>'product_id')::bigint;
  select sum(unit_price_cents::bigint * quantity) into v_total from order_lines where order_id = p_order_id;
  update orders set version = version + 1, total_cents = v_total where id = p_order_id;

  return jsonb_build_object('outcome', 'edited', 'order', order_view(p_order_id));
end $$;

-- ─── confirm_order ───────────────────────────────────────────────────────────────────────────────

-- The claim: pending -> confirmed and the stock taken, in one transaction, at most once per order.
-- Outcomes: confirmed | already_confirmed (the same p_key claimed it before: a resend) | not_found |
-- not_pending | version_conflict | insufficient_stock (with shortages; nothing written).
--
-- The order row is locked first. A second confirm waits on that lock and, once the first commits,
-- reads the row as confirmed and leaves without touching stock. Stock rows are then locked in
-- product id order, so two confirms over overlapping products cannot wait on each other in a circle.
create or replace function confirm_order(p_order_id bigint, p_expected_version integer, p_key text)
returns jsonb
language plpgsql
volatile
security invoker
set search_path = public
set lock_timeout = '5s'
as $$
declare
  v_order     orders;
  v_shortages jsonb;
begin
  perform validate_key(p_key);
  if p_order_id is null or p_expected_version is null then
    raise exception 'missing order id or version' using errcode = '22023';
  end if;

  select * into v_order from orders where id = p_order_id for update;
  if not found then
    return jsonb_build_object('outcome', 'not_found');
  end if;
  if v_order.status = 'confirmed' then
    if v_order.confirm_key = p_key then
      return jsonb_build_object('outcome', 'already_confirmed', 'order', order_view(p_order_id));
    end if;
    return jsonb_build_object('outcome', 'not_pending', 'status', v_order.status);
  end if;
  if v_order.version <> p_expected_version then
    return jsonb_build_object('outcome', 'version_conflict', 'current_version', v_order.version);
  end if;

  perform 1 from stock
   where product_id in (select product_id from order_lines where order_id = p_order_id)
   order by product_id
     for update;
  -- A product with no stock row has nothing on hand.
  select coalesce(jsonb_agg(jsonb_build_object('product_id', l.product_id, 'requested', l.quantity,
                                               'on_hand', coalesce(s.on_hand, 0))
                            order by l.product_id), '[]'::jsonb) into v_shortages
    from order_lines as l
    left join stock as s on s.product_id = l.product_id
   where l.order_id = p_order_id and coalesce(s.on_hand, 0) < l.quantity;
  if jsonb_array_length(v_shortages) > 0 then
    return jsonb_build_object('outcome', 'insufficient_stock', 'shortages', v_shortages);
  end if;

  update stock as s set on_hand = s.on_hand - l.quantity
    from order_lines as l
   where l.order_id = p_order_id and s.product_id = l.product_id;
  update orders set status = 'confirmed', confirm_key = p_key, confirmed_at = now() where id = p_order_id;

  return jsonb_build_object('outcome', 'confirmed', 'order', order_view(p_order_id));
end $$;

-- The re-read for a confirm whose response was lost.
create or replace function get_order(p_order_id bigint)
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
  select case when v is null then jsonb_build_object('outcome', 'not_found')
              else jsonb_build_object('outcome', 'found', 'order', v) end
    from (select order_view(p_order_id) as v) as x
$$;

-- ─── Privileges ──────────────────────────────────────────────────────────────────────────────────

-- Only the server calls these. Supabase grants anon and authenticated every privilege on new tables
-- and EXECUTE on new functions by default; RLS with no policies already stops the table access, and
-- these revokes are a backstop. The do-block lets the file run on a database without those roles.
alter table products    enable row level security;
alter table stock       enable row level security;
alter table orders      enable row level security;
alter table order_lines enable row level security;

revoke all on function validate_lines(jsonb) from public;
revoke all on function order_fingerprint(jsonb) from public;
revoke all on function order_view(bigint) from public;
revoke all on function in_resend_window(timestamptz) from public;
revoke all on function resend_outcome(orders, text, text) from public;
revoke all on function validate_key(text) from public;
revoke all on function place_order(text, text, jsonb) from public;
revoke all on function find_order(text, text) from public;
revoke all on function edit_order(bigint, integer, jsonb) from public;
revoke all on function confirm_order(bigint, integer, text) from public;
revoke all on function get_order(bigint) from public;

do $$
declare
  v_role text;
  v_functions text := 'validate_lines(jsonb), order_fingerprint(jsonb), order_view(bigint),
    in_resend_window(timestamptz),
    resend_outcome(orders, text, text), validate_key(text), place_order(text, text, jsonb),
    find_order(text, text), edit_order(bigint, integer, jsonb), confirm_order(bigint, integer, text),
    get_order(bigint)';
begin
  -- One role at a time: a single statement naming both would fail as a whole, and be skipped, on a
  -- database that has only one of them.
  for v_role in select rolname from pg_roles where rolname in ('anon', 'authenticated') loop
    execute format('revoke all on table products, stock, orders, order_lines from %I', v_role);
    execute format('revoke all on sequence products_id_seq, orders_id_seq from %I', v_role);
    execute format('revoke all on function %s from %I', v_functions, v_role);
  end loop;
  -- A security invoker function runs its helpers with the caller's rights, so the server role needs
  -- EXECUTE on them too.
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute format('grant execute on function %s to service_role', v_functions);
  end if;
end $$;
