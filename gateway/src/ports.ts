/**
 * What the gateway depends on, as interfaces. Production wires a database (sql/schema.sql is the
 * reference); tests and the example use the in-memory stores in memory-store.ts.
 *
 * Stores return `unknown` from reads and the gateway validates with zod (config.ts, cost.ts): a
 * row from a database is an external boundary.
 */
import type { AttemptUsage } from './cost.ts';
import type { Effort } from './models.ts';

export interface Clock {
  /** Wall-clock time: cap windows and price validity. It can jump backwards when the system clock is adjusted. */
  now(): Date;
  /** A monotonic reading in milliseconds, for durations. The value alone is not a date. */
  monotonicMs(): number;
}

export const systemClock: Clock = { now: () => new Date(), monotonicMs: () => performance.now() };

export type LogValue = string | number | boolean | null | readonly string[];
export type LogData = Readonly<Record<string, LogValue>>;

/** Structured events. The data holds ids, counts, codes and costs; never prompt or response text. */
export interface EventLog<E extends string = string> {
  log(event: E, data: LogData): void;
}

/** One JSON line per event. Defaults to console.warn. */
export function jsonLinesLog(source: string, write: (line: string) => void = (line) => console.warn(line)): EventLog {
  return {
    log(event, data) {
      // source and event go last so a data field with the same name cannot overwrite them.
      write(JSON.stringify({ ...data, source, event }));
    },
  };
}

/** Reads configuration. The signal is the call's (its deadline and the caller's): a cut read must fail. */
export interface ConfigStore {
  /** The task's config row, or null. */
  taskConfig(task: string, signal?: AbortSignal): Promise<unknown>;
  /** The single global caps row, or null. */
  globalCaps(signal?: AbortSignal): Promise<unknown>;
  /** The user's own caps row, or null if the user has none (the gateway then fails closed). */
  accountCaps(userId: string, signal?: AbortSignal): Promise<unknown>;
}

export interface UsageWindows {
  readonly dayStart: Date;
  readonly monthStart: Date;
  readonly userId: string | null;
  readonly jobId: string | null;
  /** A reservation to leave out of the totals: the calling one, in the gateway's second cap check. */
  readonly excludeId?: string;
}

/**
 * One ledger row. The ledger is append-only: a call writes a reservation before calling and a
 * second row that closes it (`replaces` = the reservation's id). Nothing is updated or deleted.
 * The id is generated by the gateway, so retrying an insert does not double the cost.
 */
export interface UsageRow {
  readonly id: string;
  /** Written before calling, at the call's worst case. Closed by the row whose `replaces` names it. */
  readonly reservation: boolean;
  /** The reservation this row closes. Null on a reservation. */
  readonly replaces: string | null;
  readonly userId: string | null;
  readonly task: string;
  readonly jobId: string | null;
  readonly effort: Effort;
  readonly promptVersion: string;
  readonly modelRequested: string;
  /** response.model: another model after a server-side fallback. Null when unknown (reservation, early cut, unbilled error). */
  readonly modelResponded: string | null;
  readonly inputTokens: number;
  readonly outputTokens: number;
  readonly cacheReadTokens: number;
  readonly cacheWrite5mTokens: number;
  readonly cacheWrite1hTokens: number;
  /** Part of outputTokens that was thinking. Null if the API did not report it, or with several attempts. */
  readonly thinkingTokens: number | null;
  /** US$ at the price in force for each model. Null when any model is unpriced or usage was incomplete. */
  readonly costUsd: number | null;
  readonly stopReason: string | null;
  readonly refusalCategory: string | null;
  /** Per-attempt breakdown when a fallback ran, so cost can be recomputed once a missing price is loaded. */
  readonly attempts: readonly AttemptUsage[] | null;
  readonly requestId: string | null;
  readonly durationMs: number | null;
  /** Bounds the output of one attempt: the worst case for an incomplete row. */
  readonly maxTokens: number;
  /** The call was cut before the API reported all usage. Caps value it at its worst case. */
  readonly incomplete: boolean;
  /** Input bound for an incomplete row whose input was never measured. */
  readonly estimatedInputTokens: number | null;
  /** The failure code (timeout, overloaded...), or null if the call ended normally. */
  readonly errorCode: string | null;
}

export interface UsageStore {
  /** What the caps need (UsageTotals in config.ts), unvalidated. With the call's signal, like the config reads. */
  totalsForCaps(windows: UsageWindows, signal?: AbortSignal): Promise<unknown>;
  /**
   * Appends a row. If a row with that id is already there (a retried insert whose first response
   * was lost), it must succeed without writing a second one. Called without the call's signal:
   * what a cut call spent is recorded anyway.
   */
  record(row: UsageRow): Promise<void>;
}

export interface PriceStore {
  /** Price rows (PriceRow in cost.ts) for these models valid at or before `at`, unvalidated. */
  pricesFor(models: readonly string[], at: Date): Promise<unknown>;
}
